function RelayProfileDetail({
  profile,
  relayFiles,
  form,
  isNew = false,
  onBack,
  onFormChange,
  onSaved,
  actions,
}: {
  profile: RelayProfile;
  relayFiles: RelayFilesResult | null;
  form: BackendSettings;
  isNew?: boolean;
  onBack: () => void;
  onFormChange: (value: BackendSettings) => void;
  onSaved?: () => void;
  actions: Actions;
}) {
  const [draft, setDraft] = useState<RelayProfile>(profile);
  const isActive = !isNew && profile.id === form.activeRelayId;
  useEffect(() => {
    setDraft(
      deriveRelayProfileFromFiles(
        isActive && relayFiles
          ? {
            ...profile,
            configContents: relayFiles.configContents,
            authContents: relayFiles.authContents,
          }
          : profile,
      ),
    );
  }, [profile.id, isActive, isNew, relayFiles?.configContents, relayFiles?.authContents]);
  const saveDraft = async () => {
    const liveFiles = isActive ? await actions.refreshRelayFiles() : null;
    // For non-active profiles, capture auth from .codex if profile has no saved auth
    const shouldCaptureFromCodex = !isActive && !draft.authContents?.trim();
    const capturedLiveFiles = shouldCaptureFromCodex ? await actions.refreshRelayFiles() : liveFiles;
    const draftForSave =
      (isActive && liveFiles) || (shouldCaptureFromCodex && capturedLiveFiles)
        ? deriveRelayProfileFromFiles({
          ...draft,
          configContents: (isActive && liveFiles ? liveFiles : capturedLiveFiles)?.configContents ?? draft.configContents,
          authContents: (isActive && liveFiles ? liveFiles : capturedLiveFiles)?.authContents ?? draft.authContents,
        })
        : deriveRelayProfileFromFiles(draft);
    const normalizedDraft = draftForSave;
    const next = isNew
      ? addRelayProfile(form, normalizedDraft)
      : updateRelayProfile(form, profile.id, normalizedDraft);
    onFormChange(next);
    await actions.saveSettingsValue(next, true);
    if (isActive) {
      await actions.saveRelayFile(
        "config",
        effectiveRelayConfigPreview(normalizedDraft, form, normalizedDraft),
        true,
      );
      await actions.saveRelayFile("auth", normalizedDraft.authContents, true);
    }
    onSaved?.();
  };
  const switchDraft = () => {
    if (isNew) return;
    const normalizedDraft = deriveRelayProfileFromFiles(draft);
    const next = syncLegacyRelayFields({
      ...form,
      relayProfiles: form.relayProfiles.map((item) => (item.id === profile.id ? normalizedDraft : item)),
      activeRelayId: profile.id,
    });
    void actions.switchRelayProfile(next);
  };
  return (
    <div className="relay-detail-page">
      <div className="relay-detail-sticky">
        <Toolbar>
          <Button onClick={onBack} variant="secondary">
            <ArrowLeft className="h-4 w-4" />
            {localizeText("返回列表")}
          </Button>
          <Button onClick={() => void saveDraft()}>
            <Save className="h-4 w-4" />
            {localizeText("保存")}
          </Button>
        </Toolbar>
      </div>
      <RelayProfileEditor profile={draft} form={form} isNew={isNew} onProfileChange={setDraft} onSwitch={switchDraft} actions={actions} />
      <RelayFileEditors
        contextProfile={profile}
        profile={draft}
        form={form}
        isActive={isActive}
        profileId={profile.id}
        onFormChange={onFormChange}
        onProfileChange={setDraft}
        actions={actions}
      />
    </div>
  );
}

