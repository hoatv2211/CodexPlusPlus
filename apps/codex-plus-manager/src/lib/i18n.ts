export function translateLiteral(language: Language, text: string) {
  if (!text) return text;
  const exact = literalTranslations[language][text];
  if (exact) return exact;

  let result = text;
  for (const [source, target] of Object.entries(literalTranslations[language])) {
    result = result.replaceAll(source, target);
  }
  return result;
}

export function setCurrentLanguage(language: Language) {
  currentLanguage = language;
}

export function localizeCurrentText(text: string) {
  return translateLiteral(currentLanguage, text);
}
